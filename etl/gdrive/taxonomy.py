"""
Таксономія (кодифікатор) документів клієнтів.

Структура коду документа:  ZV-BB.TT
  BB — блок справи з каталогу полів CRM (01 … 26, "Довідник блоків")
  TT — тип первинного документа всередині блоку
  ZV-00.xx — службові / нерозпізнані файли

Код екземпляра документа в реєстрі:  ZV-BB.TT-<КЛІЄНТ>-NNNN
  <КЛІЄНТ> — 8 символів, стабільний ключ папки клієнта на Google Диску
  NNNN     — порядковий номер документа цього типу у клієнта (за createdTime)

Кожен тип документа зв'язаний з полями CRM двома способами:
  evidence    — (блок, «Первинний документ-доказ») з аркуша «Поля → юридичний сенс»:
                усі поля, які заповнюються/підтверджуються цим документом;
  scan_fields — file-поля CRM, куди кладеться скан саме цього документа.
Для вихідних документів справи (Заява, Декларація, …) поля беруться з колонок ✔.

patterns        — регулярки по назві файлу (нормалізованій, див. classifier.normalize)
folder_patterns — регулярки по назвах папок на шляху до файлу
parse           — підказка парсеру: ocr | text | table | skip
"""

