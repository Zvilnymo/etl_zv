_CREDITOR_SLOT = re.compile(r'кредитор\s+(\d+)\s*\(для кск\)', re.IGNORECASE)


def _aspect(name: str, ftype: str, topic: str):
    """Повертає (опис аспекту, роль або None)."""
    n = name.lower()
    if ftype == 'file':
        return 'Скан / файл первинного документа (сам доказ, додається до заяви)', R_EVIDENCE
    if re.search(r'\bстатус', n) and ftype in ('enumeration', 'boolean'):
        return 'Статус збору / перевірки документа в чек-листі — сам не є доказом', R_CONTROL
    if re.search(r'комент', n):
        return 'Робочий коментар юриста по блоку — до суду не подається', R_NOTE
    if 'bot json' in n or '(bot)' in n:
        return 'Дані від клієнта через бот (самодекларація / розпізнані документи) — потребують підтвердження ' \
               'первинним документом', R_SCREEN
    if re.search(r'серія|серії|№|від _|від__|ким видан|виданий|видано|відповідно до|дата видачі|актового запису', n):
        return 'Реквізити документа для посилання в тексті («відповідно до … серії … № … від …»)', R_REQUISITES
    if re.search(r'автоформул|атоформул|\(автозаповнення\)', n):
        return 'Автоматичний розрахунок CRM', R_CALC
    if ftype in ('money', 'double', 'integer') and topic in ('income', 'income_family', 'expenses', 'pm', 'debt', 'exec', 'creditor'):
        return 'Числове значення для вписування в документ / розрахунку', None
    return '', None


def classify(code: str, name: str, ftype: str) -> dict:
    """Повертає юридичну класифікацію поля."""
    name = (name or '').strip()
    ov = OVERRIDES.get(code, {})
    topic = ov.get('topic')

    slot = _CREDITOR_SLOT.search(name)
    if not topic and slot:
        topic = 'creditor'
        ov = dict(role=R_REQUISITES,
                  sense=f'посилання на картку кредитора №{slot.group(1)} (назва, ЄДРПОУ, адреса, сума вимоги) — '
                        f'рядок №{slot.group(1)} переліку кредиторів у заяві; КСК — комплект для суду')

    if not topic and (code in SYSTEM_CODES or code.startswith(SYSTEM_PREFIXES)):
        topic = 'system'
    if not topic:
        for rx, t in _COMPILED:
            if rx.search(name):
                topic = t
                break
    if not topic:
        topic = next((t for prefix, t in CODE_PREFIX_TOPICS if code.startswith(prefix)), None)

    if not topic:
        return dict(block='99. Не класифіковано', what=clean_name(name), sense='', evidence='', docs=[], norm='', role=R_UNKNOWN,
                    aspect='', note='Потрібна ручна класифікація', topic='')

    block, base_sense, evidence, docs, norm, role = TOPICS[topic]
    aspect, aspect_role = _aspect(name, ftype, topic)

    if code in SCREENING_CODES:
        role = R_SCREEN
        aspect = 'Відповідь клієнта на етапі продажу (скринінг): показує, які документи треба зібрати; сам не є доказом'
        docs = []
    elif 'role' in ov:
        role = ov['role']
        if aspect_role and aspect_role != role:
            aspect = ''
    elif aspect_role and topic not in ('system', 'sales', 'service_contract', 'logistics', 'secret'):
        role = aspect_role

    if role in (R_CONTROL, R_NOTE, R_SCREEN, R_SYSTEM) and 'docs' not in ov:
        docs = []
    docs = ov.get('docs', docs)

    return dict(block=block, what=ov.get('sense') or clean_name(name), sense=base_sense,
                evidence=ov.get('evidence', evidence), docs=list(docs), norm=ov.get('norm', norm),
                role=role, aspect=aspect, note=ov.get('note', ''), topic=topic)


def clean_name(name: str) -> str:
    """Назва поля без шаблонних підкреслень: «№ "____ від __.__.____"» → «№ … від …»."""
    s = re.sub(r'[_]{2,}|_\.|\._|(?<=\s)_(?=\s)', '…', name)
    s = re.sub(r'(…[\s.]*)+', '… ', s)
    s = re.sub(r'"{2,}', '"', s)
    s = re.sub(r'\s+', ' ', s).strip()
    return s
